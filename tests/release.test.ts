    commit(repo.lib, "shots: rebaseline (and a radius)");
    r = await release(repo, ["1.0.1"]);
    expect(r.stderr).toContain("require a major");

    // A new baseline (a new story) is a minor.
    repo = await released();
    write(repo.lib, "gallery/__screenshots__/1440/workforce/tag--default.png", "png-3");
    addSection(repo, "## 1.0.1 — 2026-10-01\nAdded: a Tag story.\n");
