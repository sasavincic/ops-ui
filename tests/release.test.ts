const FIRST_CHANGELOG =
  "# Changelog\n\n## 1.0.0 — 2026-09-30\nAdded: the kit.\nVisible: none (a pure extraction).\nUpgrade steps: none (the first release).\n";

type Repo = { lib: string; origin: string; gateLog: string };

/** A library at 0.0.0 with its origin, everything pushed. */
function library(changelog = FIRST_CHANGELOG): Repo {
  const origin = dir("origin");
  git(origin, "init", "-q", "--bare", "-b", "main");
  const lib = dir("lib");
  git(lib, "init", "-q", "-b", "main");
  git(lib, "remote", "add", "origin", origin);
  const scripts = Object.fromEntries(["typecheck", "lint", "test", "shots"].map((g) => [g, `node gate.cjs ${g}`]));
  write(lib, "package.json", `${JSON.stringify({ name: "@latro/ops-ui", version: "0.0.0", private: true, scripts, peerDependencies: PKG.peerDependencies }, null, 2)}\n`);
  write(lib, "gate.cjs", GATE);
  write(lib, "src/version.ts", '/** The released version. */\nexport const OPS_UI_VERSION = "0.0.0";\n');
  write(lib, "src/components/button.tsx", BUTTON);
  write(lib, "styles/tokens.css", readSource("styles/tokens.css"));
  write(lib, "api-surface.d.txt", SURFACE);
  write(lib, "CHANGELOG.md", changelog);
  write(lib, "gallery/__screenshots__/1440/workforce/button--matrix.png", "png-1");
  write(lib, "gallery/__screenshots__/375/workforce/button--matrix.png", "png-2");
  write(lib, "gallery/playwright.config.ts", "// pinned\n");
  commit(lib, "L1: scaffold");
  return { lib, origin, gateLog: path.join(dir("log"), "gates.log") };
}

function commit(lib: string, subject: string, pushIt = true) {
  git(lib, "add", "-A");
  git(lib, "commit", "-q", "-m", subject);
  if (pushIt) git(lib, "push", "-q", "origin", "main");
}

async function release(repo: Repo, args: string[], env: Record<string, string> = {}) {
  try {
    const { stdout, stderr } = await run(process.execPath, [RELEASE, ...args], {
      cwd: repo.lib,
      env: { ...process.env, ...IDENTITY, GATE_LOG: repo.gateLog, ...env },
      encoding: "utf8",
    });
    return { status: 0, stdout, stderr };
  } catch (error) {
    const e = error as { code?: number; stdout?: string; stderr?: string };
    return { status: e.code ?? -1, stdout: e.stdout ?? "", stderr: e.stderr ?? "" };
  }
}

function gatesRun(repo: Repo) {
  try {
    return readFileSync(repo.gateLog, "utf8").trim().split("\n").filter(Boolean);
  } catch {
    return [];
  }
}

/** A library released at 1.0.0 (by the script itself), with a new CHANGELOG section to write. */
async function released(): Promise<Repo> {
  const repo = library();
  const result = await release(repo, ["1.0.0"]);
  if (result.status !== 0) throw new Error(`the 1.0.0 release of the fixture failed: ${result.stderr}`);
  rmSync(repo.gateLog, { force: true });
  return repo;
}

function addSection(repo: Repo, section: string) {
  const current = read(repo.lib, "CHANGELOG.md");
  write(repo.lib, "CHANGELOG.md", current.replace("# Changelog\n\n", `# Changelog\n\n${section}\n`));
}

