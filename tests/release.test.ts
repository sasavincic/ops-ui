    write(repo.lib, "README.md", "docs\n");
    addSection(repo, "## 1.0.1 — 2026-10-01\nFixed: the README.\n");
    commit(repo.lib, "docs");
    r = await release(repo, ["1.0.1"]);
    expect(r.status, r.stderr).toBe(0);

    // The same title with library source in the commit is not exempt.
    repo = await released();
    write(repo.lib, "gallery/__screenshots__/1440/workforce/button--matrix.png", "png-1-changed");
    write(repo.lib, "src/components/button.tsx", BUTTON.replace("rounded", "rounded-md"));
